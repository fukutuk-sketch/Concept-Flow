CONTEXTS = ("*", "Operator")


def _build():
    ja = {}
    for msgid, text in JA:
        for ctx in CONTEXTS:
            ja[(ctx, msgid)] = text
    return {"ja_JP": ja}


def register():
    try:
        bpy.app.translations.unregister(__package__)
    except Exception:
        pass
    bpy.app.translations.register(__package__, _build())


def unregister():
    try:
        bpy.app.translations.unregister(__package__)
    except Exception:
        pass
